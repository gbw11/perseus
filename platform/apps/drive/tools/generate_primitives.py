#!/usr/bin/env python3
"""Generate reproducible curvature-continuous Ackermann ramp control sets.

No route or expected obstacle response is generated. The runtime search connects
these controls at its current pose, and independently checks every swept edge.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

FLOATS=('resolution wheelbase front rear half_width margin max_steer steer_rate max_velocity '
        'max_accel max_brake max_lateral_accel lookahead_min lookahead_max lookahead_time reaction_s '
        'goal_distance goal_heading tracking_error max_position_error max_heading_error max_steering_error primitive_speed '
        'primitive_duration pose_age_us live_age_us cell_age_ms deviation_cost curvature_cost switch_cost plan_horizon heuristic_weight heading_weight tracking_guard goal_straight_m max_reverse_velocity').split()
INTS=('node_limit','expansion_limit','collision_limit','steering_levels','clock_error_us','clock_lease_us','planner_budget_us','state_period_us')

def generate(profile,output):
    cfg=json.loads(profile.read_text())
    if set(cfg)!=set(FLOATS)|set(INTS)|{'kind','id','assumptions','vehicle','calibration'}:raise ValueError('profile fields differ')
    if cfg['kind'] not in ('test','approved'):raise ValueError('explicit profile kind required')
    for key in ('id','vehicle','calibration'):
        value=cfg[key]
        if not isinstance(value,str) or not 1<=len(value)<=64 or any(not(c.isascii() and (c.isalnum() or c in '-_.')) for c in value):raise ValueError('bounded profile '+key)
    for key in FLOATS:
        if type(cfg[key]) not in (int,float) or not math.isfinite(cfg[key]) or cfg[key]<=0:raise ValueError('positive finite '+key)
    for key in INTS:
        if type(cfg[key]) is not int or not 0<cfg[key]<=2**31-1:raise ValueError('positive bounded '+key)
    if cfg['node_limit']>8192 or cfg['expansion_limit']>100000 or cfg['collision_limit']>100000000:raise ValueError('compiled resource caps')
    if cfg['max_steer']>=math.pi/2 or 2*cfg['max_steer']/cfg['primitive_duration']>cfg['steer_rate']:raise ValueError('steering continuity/rate')
    if cfg['lookahead_max']<cfg['lookahead_min'] or cfg['primitive_speed']>cfg['max_velocity']:raise ValueError('profile speed/lookahead')
    if cfg['goal_straight_m']>cfg['plan_horizon']:raise ValueError('goal settling distance exceeds horizon')
    if cfg['steering_levels']!=9:raise ValueError('compiled steering dimension differs')
    encoded=json.dumps(cfg,sort_keys=True,separators=(',',':')).encode()
    digest=hashlib.sha256(encoded).hexdigest()
    generator_hash=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    asset_hash=hashlib.sha256(encoded+b'\0'+generator_hash.encode()).hexdigest()
    lines=['/* SPDX-License-Identifier: Apache-2.0 */','/* Generated by generate_primitives.py; do not edit. */',
           '#include "lattice.h"','const struct lp_config lp_selected_config={',
           *[f' .{key}={json.dumps(cfg[key])},' for key in ('id','vehicle','calibration')]]
    for key in FLOATS:lines.append(f' .{key}={float(cfg[key]):.9e}f,')
    for key in INTS:lines.append(f' .{key}={cfg[key]},')
    lines+=['};','const struct lp_assets lp_selected_assets={',f' .id={json.dumps(cfg["id"])},.sha256="{asset_hash}",']
    for name,key in (('resolution','resolution'),('wheelbase','wheelbase'),('max_steer','max_steer'),('steer_rate','steer_rate'),('speed','primitive_speed'),('duration','primitive_duration')):
        lines.append(f' .{name}={float(cfg[key]):.9e}f,')
    lines.append(' .motion={')
    levels=[cfg['max_steer']*(i-4)/4 for i in range(9)]
    samples=[];dt=cfg['primitive_duration']/16
    for initial in levels:
        lines.append('  {');group=[]
        for final in levels:
            x=y=yaw=0.;points=[(x,y,yaw,initial)]
            for k in range(1,17):
                mid=initial+(final-initial)*(k-.5)/16
                turn=cfg['primitive_speed']/cfg['wheelbase']*math.tan(mid)*dt
                distance=cfg['primitive_speed']*dt
                if abs(turn)<1e-12:x+=distance*math.cos(yaw);y+=distance*math.sin(yaw)
                else:
                    radius=distance/turn
                    x+=radius*(math.sin(yaw+turn)-math.sin(yaw));y-=radius*(math.cos(yaw+turn)-math.cos(yaw))
                yaw+=turn
                points.append((x,y,yaw,initial+(final-initial)*k/16))
            group.append(points)
            lines.append('   {'+','.join('{'+','.join(f'{v:.9e}f' for v in p)+'}' for p in points)+'},')
        samples.append(group);lines.append('  },')
    lines+=[' }','};','']
    output.mkdir(parents=True,exist_ok=True)
    (output/'primitives.c').write_text('\n'.join(lines))
    (output/'primitive-manifest.json').write_text(json.dumps(dict(profile=cfg,profile_sha256=digest,asset_sha256=asset_hash,generator_sha256=generator_hash,
        states=81,samples_per_primitive=17,forward_only=True,in_place_or_holonomic_controls=False,
        root_targets=9,interior_target_indices=[0,2,4,6,8],heading_bins=32,xy_bin_m=cfg['resolution'],
        primitive_source_sha256=hashlib.sha256((output/'primitives.c').read_bytes()).hexdigest()),indent=2)+'\n')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile',type=Path,required=True);parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();generate(args.profile,args.output)

if __name__=='__main__':main()
