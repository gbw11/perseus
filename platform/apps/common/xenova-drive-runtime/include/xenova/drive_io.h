/* Single v1 owner. Copies cross the exchange lock; no I/O runs under it. */
#ifndef XENOVA_DRIVE_IO_H
#define XENOVA_DRIVE_IO_H
#include "xm_zclient.h"
struct xd_received {
 char payload[XM_MAX_DRIVING_BYTES + 1];
 char sender[XM_ID_MAX + 1], boot[XM_UUID_LEN + 1], instance[XM_UUID_LEN + 1];
 size_t length;
 int64_t received_ms, seq;
 int error; /* Copy/envelope availability; payload validity is parsed by main. */
};
struct xd_inputs {
 struct xd_received control, input;
 uint64_t control_revision, connection_revision;
 bool connected; /* CONNACK observed, not SUBACK or control re-confirmation. */
};
struct xd_candidate {
 uint64_t id, created_us, queued_us, capture_us, control_revision, connection_revision;
 int64_t expires_ms;
 char topic[XM_TOPIC_MAX], json[160];
};
enum xd_disposition { XD_SENT, XD_SEND_FAILED, XD_REPLACED, XD_EXPIRED, XD_CONTEXT_CHANGED, XD_STOPPED };
struct xd_delivery {
 uint64_t id, created_us, queued_us, taken_us, send_begin_us, send_end_us, capture_us;
 uint32_t message, topic_seq;
 int rc;
 enum xd_disposition disposition;
};
struct xd_io_stats {
 uint64_t enqueued, replaced, expired, context_dropped, stopped, attempted, sent, failed;
 uint64_t event_dropped, heartbeat_replaced, heartbeat_dropped, heartbeat_expired, snapshot_busy;
 uint64_t prepare_max_us, poll_max_us, exchange_max_us;
 bool started, joined;
 int close_error, clock_error, stack_error;
 size_t stack_unused_bytes;
};
int xd_io_start(struct xm_zclient *, const char *control, const char *input);
int xd_io_snapshot(struct xd_inputs *);
/* On acceptance, queued_us is set to the actual exchange admission time. */
int xd_io_command(struct xd_candidate *);
/* Only reports generated by a completed calculation may be offered. */
int xd_io_report(const char *topic, const char *type, const char *json,
                 uint64_t completed, const struct xd_inputs *context);
void xd_io_stop_request(void);
int xd_io_join(int64_t deadline_ms);
int xd_io_stats_get(struct xd_io_stats *);
/* Runtime-owned local capture callbacks; never create a heartbeat or drive step. */
int xd_owner_prepare(struct xm_zclient *, const char *, const char *);
bool xd_owner_admit(void);
void xd_delivery_record(const struct xd_delivery *);
#endif
