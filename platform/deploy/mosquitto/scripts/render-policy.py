#!/usr/bin/env python3
"""공통 정책에서 로컬 개발용 계정 목록과 ACL을 생성하거나 차이를 검사한다.

비밀번호·운영 계정은 읽거나 쓰지 않는다. 제품 이미지는 개발용 UUID를 사용하지 않는다.
"""
import argparse
from pathlib import Path
import sys
from xenova_broker import acl, default_accounts, policy

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rules = policy(ROOT / 'etc/policy.json')
    records = default_accounts(rules, rules['development_vm_ids'])
    expected = {'accounts': '# Generated by scripts/render-policy.py; passwords are never source inputs.\n' +
                '\n'.join(sorted(records)) + '\n', 'acl': acl(records, rules)}
    for name, value in expected.items():
        path = ROOT / 'etc' / name
        if args.check:
            if path.read_text() != value:
                print('policy output differs: ' + name, file=sys.stderr)
                return 1
        else:
            path.write_text(value, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
